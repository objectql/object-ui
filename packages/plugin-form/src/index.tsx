/**
 * The CREATE-payload rule this package owns, published for the OTHER form
 * renderer (objectui#6059).
 *
 * `omitServerResolvedDefaults` is a pure function over a values object and an
 * object schema — no React, no registry, no container — and it is the
 * COMPOSITION of two `@object-ui/core` predicates (`isRuntimeDefault` AND
 * `isMissingForRequired`, on create only) rather than a third opinion about
 * either. It stayed module-private through the whole #4047 / #4068 / #4069 /
 * #4085 / #5683 / #5727 / #5883 chain, so the console's `FormPage` — the SECOND
 * form renderer in this repo — had to spell that composition out by hand for
 * #5883, and the next renderer would have had to as well. Neither PREDICATE was
 * ever copied (both live in `@object-ui/core` precisely so they cannot fork),
 * but two hand-written copies of the composition are still free to disagree
 * about a case neither author had in mind. One importable function is not.
 *
 * `isRequiredInForm` travels with it because each one's docblock names the
 * other as its half: excusing a server-owned field from `required` and then
 * submitting the key anyway is not half a fix, it is no fix. A consumer able to
 * reach one and not the other can build exactly that state, which is the defect
 * #4069 and #5883 closed on the two chains separately.
 *
 * Deliberately NOT the rest of `schemaDefaults.ts`. `seedCreateValues`,
 * `schemaDefaultValues`, `isSeedableDefault`, `isCreateFormMode` and
 * `SeedContext` are adjacent, not asked for — no consumer outside this package
 * has needed them, and every added name is published surface somebody then has
 * to keep. `isRuntimeDefault` stays out for a stronger reason: it is
 * `@object-ui/core`'s to publish, this module only re-exports it for its own
 * call sites, and a second published spelling of one classifier is the very
 * thing #4085 collapsed.
 */
export { omitServerResolvedDefaults, isRequiredInForm } from './schemaDefaults';

// Register object-form component
const ObjectFormRenderer: React.FC<{ schema: any; dataSource?: unknown }> = elementDataSourceBlock(({
  schema,
  dataSource: dataSourceProp,
}) => {
  // ObjectForm needs a dataSource to fetch the object schema and auto-generate
  // its fields. Without one, an `object-form` rendered straight through
  // SchemaRenderer (e.g. the Studio view preview) has no fields.
  //
  // Resolved through the family's shared rule (objectui#5378): an explicit
  // adapter first, the `SchemaRendererProvider` context second. The explicit
  // half is additive — this block used to read context ONLY, so nothing that
  // worked before resolves differently now; what changes is that the three
  // blocks in the family no longer answer "where does the adapter come from?"
  // three different ways, which is the split that made the getting-started
  // guide satisfiable by neither wiring.
  const dataSource = useResolvedDataSource<DataSource>(dataSourceProp);
  // The spec's `PageComponentSchema.dataSource` binding (objectstack#6953). A
  // page that declared `dataSource: { object }` and no `objectName` rendered a
  // field-less shell: `ObjectForm` gates its whole schema fetch on `objectName`.
  //
  // `object` is the ONLY key of the binding this block can honour, and the
  // mapping says so rather than parking the rest somewhere plausible. A form
  // edits ONE record — it has no collection query, so there is nothing for
  // `filter` / `sort` / `limit` to narrow, and a saved LIST view's columns are
  // not a form layout (`fields` here is an ordered layout, not a projection).
  // A `view` name is still resolved, so naming one that does not exist reports
  // instead of rendering; a view that DOES resolve contributes nothing on this
  // block, which is recorded as the residual gap on objectstack#6953.
  return (
    <ElementDataSourceGate
      schema={schema}
      dataSource={dataSource}
      testId="object-form"
      errorTitle="This form’s data source could not be resolved"
      // `ObjectForm` builds its fields from the object's metadata, which only an
      // adapter can serve — its own effect calls the branch it comments as
      // "cannot proceed" and then renders a field-less card in silence
      // (objectui#5378 item 2). The one escape hatch is inline `customFields`,
      // which is exactly what `hasInlineFields` gates on inside the component,
      // so the two stay in step. A form with no `objectName` is a different
      // defect and is left to report itself.
      requiresDataSource={
        !(schema?.customFields?.length > 0)
        && typeof schema?.objectName === 'string'
        && schema.objectName.length > 0
      }
      noDataSourceMessage={noDataSourceMessage('object-form', schema?.objectName)}
    >
      {(bound) => <ObjectForm schema={bound} dataSource={dataSource} />}
    </ElementDataSourceGate>
  );
});

